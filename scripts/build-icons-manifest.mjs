// Scans the local `icons/` directory (icons copied straight out of the
// Factorio install: data/base/graphics/, data/space-age/graphics/,
// data/quality/graphics/) and writes a flat `category_name → relative URL`
// manifest as `src/icons-manifest.js`.
//
// File layout we expect:
//   icons/<root>/icons/<name>.png                  → icons_<name>
//   icons/<root>/icons/<subcat>/<name>.png         → <subcat>_<name>
//   icons/<root>/<topcat>/<name>.png               → <topcat>_<name>
//
//   where <root> is base | space-age | quality | …
//   <topcat> is icons | achievement | equipment | technology | item-group | …
//   <subcat> is signal | arrows | shapes | fluid | parameter | …
//
// Names are normalised: `_` in filenames becomes `-` so that, e.g.,
// `signal/signal_1.png` ends up as the key `signal_signal-1` — this
// matches the dashed names Factorio writes inside blueprint JSON
// (`{ name: "signal-1" }`).
//
// Run via `npm run icons:update` after adding / removing icons in the
// `icons/` folder.

import { readdirSync, statSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const ICONS_ROOT = 'icons'

// First-write-wins ordering. `base` first because, in Factorio data,
// base/icons/ is the canonical home for shared items and we'd rather
// pick it up before any DLC-specific override happens to land on top.
const ROOT_ORDER = ['base', 'space-age', 'elevated-rails', 'quality']

function* walkPngs(dir, prefix = '') {
  let entries
  try { entries = readdirSync(dir) } catch { return }
  // Stable order for determinism.
  entries.sort()
  for (const entry of entries) {
    const full = join(dir, entry)
    const rel = prefix ? `${prefix}/${entry}` : entry
    let st
    try { st = statSync(full) } catch { continue }
    if (st.isDirectory()) {
      yield* walkPngs(full, rel)
    } else if (entry.toLowerCase().endsWith('.png')) {
      yield rel
    }
  }
}

function pathToKey(relPath) {
  const parts = relPath.split('/')
  if (parts.length < 2) return null
  const filename = parts[parts.length - 1]
  if (!filename.toLowerCase().endsWith('.png')) return null
  const stem = filename.slice(0, -4).replace(/_/g, '-')

  // parts[0] is the root (base / space-age / quality / …).
  // We use the file's immediate parent folder as the category — that
  // works for every depth we care about:
  //   <root>/<topcat>/<file>             → category = topcat
  //   <root>/<topcat>/<sub>/<file>       → category = sub
  //   <root>/<topcat>/<sub>/<sub2>/<file>→ category = sub2
  if (parts.length < 3) return null
  const category = parts[parts.length - 2]

  return `${category}_${stem}`
}

function main() {
  // Discover every root folder under icons/ and walk them in priority order.
  let allRoots
  try {
    allRoots = readdirSync(ICONS_ROOT, { withFileTypes: true })
      .filter(d => d.isDirectory())
      .map(d => d.name)
  } catch (e) {
    console.error(`Could not read ${ICONS_ROOT}/: ${e.message}`)
    process.exit(1)
  }

  const orderedRoots = [
    ...ROOT_ORDER.filter(r => allRoots.includes(r)),
    ...allRoots.filter(r => !ROOT_ORDER.includes(r)).sort()
  ]

  const manifest = {}
  let totalSeen = 0
  let collisions = 0
  const collisionExamples = []

  for (const root of orderedRoots) {
    const dir = join(ICONS_ROOT, root)
    for (const rel of walkPngs(dir, root)) {
      totalSeen++
      const key = pathToKey(rel)
      if (!key) continue
      if (key in manifest) {
        collisions++
        if (collisionExamples.length < 5) {
          collisionExamples.push(`${key}: kept ${manifest[key]} over ${rel}`)
        }
        continue
      }
      // Use forward slashes regardless of host OS so the URL works in browsers.
      manifest[key] = `${ICONS_ROOT}/${rel}`
    }
  }

  // Sort keys for deterministic output, stable diffs in git.
  const sortedKeys = Object.keys(manifest).sort()
  const sorted = {}
  for (const k of sortedKeys) sorted[k] = manifest[k]

  const out = `// AUTO-GENERATED by scripts/build-icons-manifest.mjs.
// Source: local icons/ directory (icons copied from the Factorio install).
// Run \`npm run icons:update\` to regenerate.

export default ${JSON.stringify(sorted, null, 2)}
`

  writeFileSync('src/icons-manifest.js', out)
  console.log(`Walked ${totalSeen} PNG files across ${orderedRoots.length} roots.`)
  console.log(`Wrote ${sortedKeys.length} entries to src/icons-manifest.js (${collisions} collision(s) skipped).`)
  if (collisionExamples.length > 0) {
    console.log('First few collisions:')
    for (const ex of collisionExamples) console.log('  ' + ex)
  }
}

main()
